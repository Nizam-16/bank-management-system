-- ==========================================
-- 1. DATABASE SCHEMA (TABLES)
-- ==========================================

CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR2(50) NOT NULL,
    last_name VARCHAR2(50) NOT NULL,
    email VARCHAR2(100) UNIQUE NOT NULL,
    phone VARCHAR2(20),
    address VARCHAR2(200),
    created_at DATE DEFAULT SYSDATE
);

CREATE TABLE accounts (
    account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER REFERENCES customers(customer_id),
    account_type VARCHAR2(20) CHECK (account_type IN ('SAVINGS', 'CURRENT')),
    balance NUMBER(15, 2) DEFAULT 0.00 CHECK (balance >= 0),
    status VARCHAR2(10) DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'CLOSED', 'SUSPENDED')),
    created_at DATE DEFAULT SYSDATE
);

CREATE TABLE transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id NUMBER REFERENCES accounts(account_id),
    target_account_id NUMBER REFERENCES accounts(account_id),
    transaction_type VARCHAR2(20) CHECK (transaction_type IN ('DEPOSIT', 'WITHDRAWAL', 'TRANSFER')),
    amount NUMBER(15, 2) NOT NULL,
    transaction_date DATE DEFAULT SYSDATE
);

-- ==========================================
-- 2. PACKAGE SPECIFICATION
-- ==========================================

CREATE OR REPLACE PACKAGE bank_pkg AS
    insufficient_funds EXCEPTION;
    invalid_account EXCEPTION;

    PROCEDURE create_customer(
        p_first_name IN VARCHAR2,
        p_last_name IN VARCHAR2,
        p_email IN VARCHAR2,
        p_phone IN VARCHAR2,
        p_address IN VARCHAR2,
        p_customer_id OUT NUMBER
