-- ==========================================
-- 3. PACKAGE BODY
-- ==========================================

CREATE OR REPLACE PACKAGE BODY bank_pkg AS

    PROCEDURE create_customer(
        p_first_name IN VARCHAR2,
        p_last_name IN VARCHAR2,
        p_email IN VARCHAR2,
        p_phone IN VARCHAR2,
        p_address IN VARCHAR2,
        p_customer_id OUT NUMBER
    ) IS
    BEGIN
        INSERT INTO customers (first_name, last_name, email, phone, address)
        VALUES (p_first_name, p_last_name, p_email, p_phone, p_address)
        RETURNING customer_id INTO p_customer_id;
        
        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Customer created successfully with ID: ' || p_customer_id);
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Error creating customer: ' || SQLERRM);
    END create_customer;

    PROCEDURE open_account(
        p_customer_id IN NUMBER,
        p_account_type IN VARCHAR2,
        p_initial_deposit IN NUMBER,
        p_account_id OUT NUMBER
    ) IS
        v_cust_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_cust_count FROM customers WHERE customer_id = p_customer_id;
        IF v_cust_count = 0 THEN
            RAISE invalid_account;
        END IF;

        INSERT INTO accounts (customer_id, account_type, balance)
        VALUES (p_customer_id, UPPER(p_account_type), p_initial_deposit)
        RETURNING account_id INTO p_account_id;

        IF p_initial_deposit > 0 THEN
            INSERT INTO transactions (account_id, transaction_type, amount)
            VALUES (p_account_id, 'DEPOSIT', p_initial_deposit);
        END IF;

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Account opened successfully. Account ID: ' || p_account_id);
    EXCEPTION
        WHEN invalid_account THEN
            DBMS_OUTPUT.PUT_LINE('Error: Customer ID does not exist.');
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Error opening account: ' || SQLERRM);
    END open_account;

    PROCEDURE deposit(
        p_account_id IN NUMBER,
        p_amount IN NUMBER
    ) IS
        v_status VARCHAR2(10);
    BEGIN
        IF p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20001, 'Deposit amount must be greater than zero.');
        END IF;

        SELECT status INTO v_status FROM accounts WHERE account_id = p_account_id;
        IF v_status != 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20002, 'Account is not active.');
        END IF;

        UPDATE accounts 
        SET balance = balance + p_amount 
        WHERE account_id = p_account_id;

        INSERT INTO transactions (account_id, transaction_type, amount)
        VALUES (p_account_id, 'DEPOSIT', p_amount);

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Successfully deposited ' || p_amount || ' into Account ID: ' || p_account_id);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('Error: Account ID not found.');
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Error during deposit: ' || SQLERRM);
    END deposit;

    PROCEDURE withdraw(
        p_account_id IN NUMBER,
        p_amount IN NUMBER
    ) IS
        v_balance NUMBER;
        v_status VARCHAR2(10);
    BEGIN
        IF p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20003, 'Withdrawal amount must be greater than zero.');
        END IF;

        SELECT balance, status INTO v_balance, v_status 
        FROM accounts 
        WHERE account_id = p_account_id;

        IF v_status != 'ACTIVE' THEN
            RAISE_APPLICATION_ERROR(-20004, 'Account is not active.');
        END IF;

        IF v_balance < p_amount THEN
            RAISE insufficient_funds;
        END IF;

        UPDATE accounts 
        SET balance = balance - p_amount 
        WHERE account_id = p_account_id;

        INSERT INTO transactions (account_id, transaction_type, amount)
        VALUES (p_account_id, 'WITHDRAWAL', p_amount);

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Successfully withdrew ' || p_amount || ' from Account ID: ' || p_account_id);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('Error: Account ID not found.');
        WHEN insufficient_funds THEN
            DBMS_OUTPUT.PUT_LINE('Error: Insufficient funds in Account ID: ' || p_account_id);
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Error during withdrawal: ' || SQLERRM);
    END withdraw;

    PROCEDURE transfer_funds(
        p_source_account IN NUMBER,
        p_target_account IN NUMBER,
        p_amount IN NUMBER
    ) IS
        v_source_balance NUMBER;
    BEGIN
        IF p_amount <= 0 THEN
            RAISE_APPLICATION_ERROR(-20005, 'Transfer amount must be greater than zero.');
        END IF;

        IF p_source_account = p_target_account THEN
            RAISE_APPLICATION_ERROR(-20006, 'Cannot transfer funds to the same account.');
        END IF;

        SELECT balance INTO v_source_balance 
        FROM accounts 
        WHERE account_id = p_source_account 
        FOR UPDATE;

        IF v_source_balance < p_amount THEN
            RAISE insufficient_funds;
        END IF;

        UPDATE accounts SET balance = balance - p_amount WHERE account_id = p_source_account;
        UPDATE accounts SET balance = balance + p_amount WHERE account_id = p_target_account;

        INSERT INTO transactions (account_id, target_account_id, transaction_type, amount)
        VALUES (p_source_account, p_target_account, 'TRANSFER', p_amount);

        COMMIT;
        DBMS_OUTPUT.PUT_LINE('Successfully transferred ' || p_amount || ' from Account ' || p_source_account || ' to Account ' || p_target_account);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('Error: One or both account IDs not found.');
            ROLLBACK;
        WHEN insufficient_funds THEN
            DBMS_OUTPUT.PUT_LINE('Error: Insufficient funds in source account.');
            ROLLBACK;
        WHEN OTHERS THEN
            ROLLBACK;
            DBMS_OUTPUT.PUT_LINE('Error during transfer: ' || SQLERRM);
    END transfer_funds;

    FUNCTION get_balance(
        p_account_id IN NUMBER
    ) RETURN NUMBER IS
        v_balance NUMBER;
    BEGIN
        SELECT balance INTO v_balance FROM accounts WHERE account_id = p_account_id;
        RETURN v_balance;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN -1; 
    END get_balance;

END bank_pkg;
